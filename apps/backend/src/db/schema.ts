// Read as ISO 8601 strings, the form JSON responses carry, so rows need no
// date conversion. Postgres's own text form is not ISO 8601. Millisecond
// precision, as a JS Date has.
const timestamptz = customType<{ data: string; driverData: string | Date }>({
  dataType: () => "timestamp(3) with time zone",
  fromDriver: (value) => new Date(value).toISOString(),
});
const createdAt = () =>
  timestamptz()
    .notNull()
    .default(sql`now()`);
const updatedAt = () =>
  timestamptz()
    .notNull()
    .default(sql`now()`)
    .$onUpdate(() => new Date().toISOString());
// Postgres 18's uuidv7(): time-ordered, generated by the database.
const uuidv7 = () =>
  uuid()
    .notNull()
    .default(sql`uuidv7()`);

const tsvector = customType<{ data: string }>({ dataType: () => "tsvector" });

